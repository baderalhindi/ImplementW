/** Never held by an external user, nor through R08 (GrantPolicy): approval, reports, integrations and the SAR amounts. */
function internalOnly(code: PermissionCode): boolean {
  return (
    code.startsWith('APPROVAL_') ||
    code.startsWith('REPORT_') ||
    code.startsWith('INTEGRATION_') ||
    code === 'FINANCIAL_VIEW_SENSITIVE'
  );
}

/** What `user` holds through the shipped profiles of the roles assigned to them. */
export function shippedPermissions(user: SessionUser | null | undefined): EffectivePermissions {
  const held = new Map<string, Set<DataScope>>();
  for (const { roleCode } of user?.roleAssignments ?? []) {
    for (const [code, scope] of Object.entries(SHIPPED_MATRIX[roleCode] ?? {})) {
      const external = user?.userType === 'EXTERNAL' || roleCode === 'R08';
      if (external && internalOnly(code as PermissionCode)) {
        continue;
      }
      held.set(code, new Set([...(held.get(code) ?? []), scope]));
    }
  }
  return {
    permissions: [...held.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([code, scopes]) => ({ code, scopes: [...scopes] })),
  };
}

/** Every permission at every scope it ships with: for a test whose subject is a screen, not who may open it. */
export function allPermissions(): EffectivePermissions {
  return shippedPermissions({
    roleAssignments: Object.keys(SHIPPED_MATRIX).map((roleCode) => ({ roleCode })),
    userType: 'INTERNAL',
  } as SessionUser);
}
